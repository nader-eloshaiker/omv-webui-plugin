// The workspace's one orval run (docs/04, "The pipeline"). Reads the bundled contract, writes the
// TanStack Query hooks into ./src/generated and the DTOs into @omv-webui/ts-api-omv, and wires the
// transport module as the mutator. Output is committed; regenerate with `pnpm api:react:build`.
import { readFileSync } from "node:fs";
import { defineConfig } from "orval";

const CONTRACT = "../spec-api-omv/generated/openapi.json";

interface ContractOperation {
  operationId: string;
  "x-omv-readonly"?: boolean;
}

// Every operation is a POST, which orval would make a mutation. A read (x-omv-readonly) gets a query
// hook instead. The list comes from the contract on every run, so it is never maintained by hand.
const contract = JSON.parse(
  readFileSync(new URL(CONTRACT, import.meta.url), "utf8"),
) as {
  paths: Record<string, { post: ContractOperation }>;
};
const operations = Object.fromEntries(
  Object.values(contract.paths)
    .map((item) => item.post)
    .filter((op) => op["x-omv-readonly"] === true)
    .map((op) => [
      op.operationId,
      { query: { useQuery: true, useMutation: false } },
    ]),
);

export default defineConfig({
  omv: {
    input: { target: CONTRACT },
    output: {
      workspace: "src/generated",
      mode: "tags-split",
      target: "./omv",
      schemas: {
        path: "../../../ts-api-omv/src/generated/models",
        type: "typescript",
        importPath: "@omv-webui/ts-api-omv",
      },
      indexFiles: true,
      client: "react-query",
      httpClient: "axios",
      // No generated mocks: the mock answers every operation with a named example from the
      // contract (src/mocks), never with invented data.
      clean: true,
      override: {
        header: (info) => [
          "Generated by orval. Do not edit.",
          ...(info.title ? [info.title] : []),
        ],
        mutator: { path: "../transport/rpcClient.ts", name: "rpcClient" },
        query: { useQuery: false, useMutation: true, signal: true },
        operations,
      },
    },
  },
});
